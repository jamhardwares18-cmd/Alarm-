package com.example.tamilalarm

object TamilTime {

    // index = hour % 12  (0 -> 12)
    private val hourNames = arrayOf(
        "பன்னிரண்டு", "ஒரு", "இரண்டு", "மூன்று", "நான்கு", "ஐந்து",
        "ஆறு", "ஏழு", "எட்டு", "ஒன்பது", "பத்து", "பதினொரு"
    )

    private val minuteWords = arrayOf(
        "பூஜ்யம்", "ஒன்று", "இரண்டு", "மூன்று", "நான்கு", "ஐந்து", "ஆறு", "ஏழு", "எட்டு", "ஒன்பது",
        "பத்து", "பதினொன்று", "பன்னிரண்டு", "பதிமூன்று", "பதினான்கு", "பதினைந்து",
        "பதினாறு", "பதினேழு", "பதினெட்டு", "பத்தொன்பது",
        "இருபது", "இருபத்தொன்று", "இருபத்திரண்டு", "இருபத்துமூன்று", "இருபத்துநான்கு",
        "இருபத்தைந்து", "இருபத்தாறு", "இருபத்தேழு", "இருபத்தெட்டு", "இருபத்தொன்பது",
        "முப்பது", "முப்பத்தொன்று", "முப்பத்திரண்டு", "முப்பத்துமூன்று", "முப்பத்துநான்கு",
        "முப்பத்தைந்து", "முப்பத்தாறு", "முப்பத்தேழு", "முப்பத்தெட்டு", "முப்பத்தொன்பது",
        "நாற்பது", "நாற்பத்தொன்று", "நாற்பத்திரண்டு", "நாற்பத்துமூன்று", "நாற்பத்துநான்கு",
        "நாற்பத்தைந்து", "நாற்பத்தாறு", "நாற்பத்தேழு", "நாற்பத்தெட்டு", "நாற்பத்தொன்பது",
        "ஐம்பது", "ஐம்பத்தொன்று", "ஐம்பத்திரண்டு", "ஐம்பத்துமூன்று", "ஐம்பத்துநான்கு",
        "ஐம்பத்தைந்து", "ஐம்பத்தாறு", "ஐம்பத்தேழு", "ஐம்பத்தெட்டு", "ஐம்பத்தொன்பது"
    )

    fun period(h24: Int): String = when (h24) {
        0 -> "நள்ளிரவு"
        in 1..3 -> "இரவு"
        in 4..5 -> "அதிகாலை"
        in 6..11 -> "காலை"
        in 12..15 -> "மதியம்"
        in 16..18 -> "மாலை"
        else -> "இரவு"
    }

    fun hourName(h24: Int): String = hourNames[h24 % 12]

    /** "ஒரு மணிக்கு நேரம், அதிகாலை ஒரு மணி." */
    fun hourly(h24: Int): String =
        "${hourName(h24)} மணிக்கு நேரம், ${period(h24)} ${hourName(h24)} மணி."

    /** "அலாரம். இப்போது நேரம், காலை ஆறு மணி முப்பது நிமிடம்." */
    fun alarm(h24: Int, minute: Int): String {
        val mins = if (minute == 0) "" else " ${minuteWords[minute]} நிமிடம்"
        return "அலாரம். இப்போது நேரம், ${period(h24)} ${hourName(h24)} மணி$mins."
    }
}
